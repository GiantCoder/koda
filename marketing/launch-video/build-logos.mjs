// Regenerates logos.js from the brand SVGs in public/logos (run after the logo files change).
// The black lockup is used as a template: #0F0F0F -> letter colour, #C41E24 -> ball colour.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const DIR = path.dirname(fileURLToPath(import.meta.url));
const src = readFileSync(path.join(DIR, '../../public/logos/mode=black.svg'), 'utf8');
const inner = src.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  .replace(/mask0_2_\d+/g, '%ID%').replace(/#0F0F0F/g, '%K%').replace(/#C41E24/g, '%A%');
const lines = inner.trim().split('\n');
// Paths 1-15 are the mark (mask, swoosh, ring, ball trail, ball); the last two are "oda" and "cricket".
const mark = lines.slice(0, -2).join('\n'), oda = lines.at(-2), cricket = lines.at(-1);
writeFileSync(path.join(DIR, 'logos.js'),
  '// Generated by build-logos.mjs from public/logos/mode=black.svg. Do not edit by hand.\n' +
  `window.KODA_LOGO = ${JSON.stringify({ mark, oda, cricket })};\n`);
console.log('logos.js written');
